#!/bin/bash
set -euo pipefail

# Build the Debian-family package without requiring stdeb or dh-python.
#
# Build requirements:
#   python3 (>= 3.8), python3-pip, python3-setuptools, dpkg-dev
#
# Runtime dependencies are recorded in the generated package control file and
# are resolved by apt when the package is installed.

cd "$(dirname "$0")/.."

package_name="opencobolide"
package_version="${OCIDE_PACKAGE_VERSION:-4.7.6+modern11.6}"
package_root="${OCIDE_PACKAGE_ROOT:-build/deb-root}"
output_file="${OCIDE_OUTPUT_FILE:-dist/${package_name}_${package_version}_all.deb}"

rm -rf "$package_root"
mkdir -p "$package_root/DEBIAN"
mkdir -p "$package_root/usr/share/doc/$package_name"
mkdir -p "$package_root/usr/share/doc/$package_name/examples/gixsql"
mkdir -p "$package_root/usr/share/man/man1"
mkdir -p "$package_root/usr/share/applications"
mkdir -p "$package_root/usr/share/pixmaps"
mkdir -p "$package_root/usr/bin"
mkdir -p "$(dirname "$output_file")"

python3 -m pip install . \
    --target "$package_root/usr/lib/python3/dist-packages" \
    --no-deps \
    --no-build-isolation \
    --no-compile \
    --disable-pip-version-check

# A --target installation places console scripts below the target directory.
# The Debian package provides its launcher in /usr/bin instead, so discard the
# duplicate target-local script directory.
rm -rf "$package_root/usr/lib/python3/dist-packages/bin"

cat > "$package_root/usr/bin/opencobolide" <<'PY'
#!/usr/bin/python3
from open_cobol_ide.main import main

raise SystemExit(main())
PY

install -m 0644 share/OpenCobolIDE.desktop \
    "$package_root/usr/share/applications/OpenCobolIDE.desktop"
install -m 0644 share/OpenCobolIDE.png \
    "$package_root/usr/share/pixmaps/OpenCobolIDE.png"

# The Help action opens this self-contained manual without network access.
install -m 0644 doc/OpenCobolIDE-modern11.6.html \
    "$package_root/usr/share/doc/$package_name/manual.html"
# Keep the source and installed Markdown guide names identical.
for guide in README.md HOWTO_MODERN11.6.md REVIEW_MODERN11.6.md RELEASE_NOTES_MODERN11.6.md INSTALL_FROM_SOURCE.md AUTHORS.rst LICENSE; do
    install -m 0644 "$guide" "$package_root/usr/share/doc/$package_name/$guide"
done
mkdir -p "$package_root/usr/share/doc/$package_name/packaging"
install -m 0644 packaging/RPM_MODERN11.6.md "$package_root/usr/share/doc/$package_name/packaging/"
mkdir -p "$package_root/usr/share/doc/$package_name/examples"
cp -a examples/project-demo "$package_root/usr/share/doc/$package_name/examples/"
example_target="$package_root/usr/share/doc/$package_name/examples/gixsql"
install -m 0755 examples/gixsql/build.sh "$example_target/build.sh"
install -m 0644 examples/gixsql/detect_sql.py "$example_target/detect_sql.py"
install -m 0644 examples/gixsql/README.md "$example_target/README.md"
install -m 0644 examples/gixsql/gitignore.example \
    "$example_target/gitignore.example"
cp -a examples/gixsql/src examples/gixsql/copybooks examples/gixsql/config \
    "$example_target/"

# Bytecode is generated by Python on the target system when appropriate.
find "$package_root" -type d -name __pycache__ -prune -exec rm -rf {} +
find "$package_root" -type f -name '*.pyc' -delete
find "$package_root" -type f -name '*.pyo' -delete

copyright="$package_root/usr/share/doc/$package_name/copyright"
printf '%s\n' \
    'Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/' \
    'Upstream-Name: OpenCobolIDE' \
    'Source: https://github.com/OpenCobolIDE/OpenCobolIDE' \
    '' \
    'Files: *' \
    'Copyright: 2014-2016 Colin Duquesnoy and OpenCobolIDE contributors' \
    'License: GPL-3+' \
    ' This program is free software: you can redistribute it and/or modify' \
    ' it under the terms of the GNU General Public License as published by' \
    ' the Free Software Foundation, either version 3 of the License, or' \
    ' (at your option) any later version.' \
    ' .' \
    ' On Debian systems, the complete text of the GNU General Public License' \
    ' version 3 can be found in /usr/share/common-licenses/GPL-3.' \
    '' \
    'Files: open_cobol_ide/extlibs/*' \
    'Copyright: respective upstream authors' \
    'License: various' \
    ' Bundled legacy dependencies retain their upstream copyright and license' \
    ' notices in their source files and package metadata.' \
    > "$copyright"

install -m 0644 share/opencobolide.1 \
    "$package_root/usr/share/man/man1/opencobolide.1"
gzip -n -9 "$package_root/usr/share/man/man1/opencobolide.1"

changelog="$package_root/usr/share/doc/$package_name/changelog"
printf '%s\n' \
    "$package_name ($package_version) unstable; urgency=medium" \
    '' \
    '  * Consolidate the project development series under the modern11.6 version.' \
    '  * Ship updated README, how-to, development review and a portable demo project.' \
    '  * Add .cpy/.CPY creation with blank copybooks and project folder defaults.' \
    '  * Edit copybooks as COBOL while excluding standalone compile/run actions.' \
    '  * Add Close Project and isolate source tabs when switching projects.' \
    '  * Protect unsaved edits with Save/Discard/Cancel and failed-save checks.' \
    '  * Fix closed-document lifetime and detached-window cleanup.' \
    '  * Add New Project and Configure Project workflows with portable project.json.' \
    '  * Migrate legacy project/source preferences and validate settings before builds.' \
    '  * Add source-relative paths, listing controls and per-source build overrides.' \
    '  * Build opened projects with the IDE-owned script, never project build.sh.' \
    '  * Include internal SQL detection, cross-reference listings and verbose output.' \
    '  * Restore default project listings when IDE flags omit -T/-t.' \
    '  * Display GixSQL commands and verbose compile/link steps.' \
    '  * Add persistent project compiler defaults below per-source overrides.' \
    '  * Apply project defaults to compilation, syntax checking and build scripts.' \
    '  * Detect module mode from PROCEDURE DIVISION USING without inline LINKAGE.' \
    '  * Add Open Project and Compile Project while preserving F8 compilation.' \
    '  * Pass detected source mode and per-source options to GixSQL build scripts.' \
    '  * Correct About runtime diagnostics using cobcrun --info and --runtime-config.' \
    '  * Add automatic listing names and per-source compiler flag overrides.' \
    '  * Detect FREE and FIXED source directives in the editor automatically.' \
    '  * Add an opt-in durable trace log for investigating native crashes.' \
    '  * Trace compilation, child processes, shutdown, Qt, and Python faults.' \
    '  * Defer Qt reference cleanup until after the application event loop.' \
    '  * Make shutdown cleanup idempotent across Linux runtime combinations.' \
    '  * Add an optional user launcher for Linux source installation.' \
    '  * Prompt for program arguments on Run and remember them per source file.' \
    '  * Forward quoted arguments to embedded and external program consoles.' \
    '  * Preserve the original OpenCobolIDE authorship and maintainer.' \
    '  * Polish OpenCobolIDE 4.7.6 for modern Python, PyQt5, and Debian Linux.' \
    '  * Use maintained Pygments instead of its obsolete bundled copy.' \
    '  * Remove the obsolete Future compatibility dependency from artifacts.' \
    '  * Fix remaining invalid escape warnings on Python 3.12.' \
    '  * Add modern venv and pip source installation for Linux and Windows.' \
    '  * Add Linux shell and Windows PowerShell installation helpers.' \
    '  * Support launching with python -m open_cobol_ide.' \
    '  * Restore file opening on Python 3.11 and newer.' \
    '  * Pass GnuCOBOL standard names correctly on Python 3.11 and newer.' \
    '  * Add a self-contained offline HTML manual opened by the Help action.' \
    '  * Ship a reusable GixSQL build.sh template for project preprocessing.' \
    '  * Document SQLite and MariaDB runtime profiles with example conf files.' \
    '  * Add offline Help instructions for resetting a broken window layout.' \
    '  * Recommend GnuCOBOL instead of requiring the distribution package.' \
    '  * Remove obsolete release assets and runtime-unneeded bundled tests.' \
    '  * Complete compatibility and packaging work with OpenAI Codex assistance.' \
    '' \
    " -- OpenCobolIDE compatibility build <noreply@opencobolide.invalid>  $(LC_ALL=C date -R)" \
    > "$changelog"
gzip -n -9 "$changelog"

installed_size="$(du -sk "$package_root/usr" | cut -f1)"
control="$package_root/DEBIAN/control"
printf '%s\n' \
    'Package: opencobolide' \
    "Version: $package_version" \
    'Section: devel' \
    'Priority: optional' \
    'Architecture: all' \
    'Depends: python3 (>= 3.8), python3-pyqt5 (>= 5.15), python3-pygments (>= 2.11)' \
    'Recommends: gnucobol' \
    "Installed-Size: $installed_size" \
    'Maintainer: Colin Duquesnoy <colin.duquesnoy@gmail.com>' \
    'Homepage: https://github.com/OpenCobolIDE/OpenCobolIDE' \
    'Description: COBOL IDE polished for modern Debian Linux' \
    ' This unofficial modern build preserves the original project' \
    ' authorship and adds modern Python, PyQt5 and project workflows with assistance' \
    ' from OpenAI Codex. It is not a new or official upstream release.' \
    > "$control"

find "$package_root" -type d -exec chmod 0755 {} +
find "$package_root" -type f -exec chmod 0644 {} +
chmod 0755 "$package_root/usr/bin/opencobolide"
chmod 0755 \
    "$package_root/usr/share/doc/$package_name/examples/gixsql/build.sh"
chmod 0755 "$package_root/DEBIAN"
dpkg-deb --root-owner-group --build "$package_root" "$output_file"

sha256sum "$output_file"
